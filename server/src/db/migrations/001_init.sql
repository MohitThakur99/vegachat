CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- citext: Rahul@Example.com and rahul@example.com are the same account.
  email         citext NOT NULL UNIQUE,
  display_name  text NOT NULL CHECK (char_length(display_name) BETWEEN 2 AND 40),
  password_hash text NOT NULL,
  avatar_url    text,
  last_seen_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- User search is "name contains q" / "email starts with q". Trigram indexes
-- keep ILIKE off a sequential scan once the table is large.
CREATE INDEX users_display_name_trgm_idx ON users USING gin (display_name gin_trgm_ops);
CREATE INDEX users_email_trgm_idx ON users USING gin ((email::text) gin_trgm_ops);

-- ---------------------------------------------------------------------------
-- refresh_tokens: one row per issued refresh token. Only a SHA-256 hash is
-- stored, so a database leak does not hand out working sessions.
-- ---------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- All tokens descended from one login share a family, so a replayed token
  -- can revoke the whole chain.
  family_id  uuid NOT NULL,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  -- Set when this token was exchanged for a newer one (normal use).
  rotated_at timestamptz,
  -- Set on logout or when theft is detected. Final: never honoured again.
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family_id);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);

-- ---------------------------------------------------------------------------
-- conversations: direct chats and groups share one table so messages,
-- membership and receipts have a single code path.
-- ---------------------------------------------------------------------------
CREATE TABLE conversations (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  type             text NOT NULL CHECK (type IN ('direct', 'group')),
  name             text CHECK (name IS NULL OR char_length(name) BETWEEN 1 AND 60),
  avatar_url       text,
  -- "<smaller user id>:<larger user id>" for direct chats. The UNIQUE
  -- constraint is what makes a direct conversation between two people unique,
  -- including when both press "start chat" at the same moment.
  direct_key       text UNIQUE,
  created_by       uuid REFERENCES users (id) ON DELETE SET NULL,
  -- Denormalised so the sidebar can sort and count without touching messages.
  last_message_seq bigint NOT NULL DEFAULT 0,
  last_activity_at timestamptz NOT NULL DEFAULT now(),
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversations_shape_check CHECK (
    (type = 'direct' AND direct_key IS NOT NULL AND name IS NULL)
    OR (type = 'group' AND direct_key IS NULL AND name IS NOT NULL)
  )
);

-- ---------------------------------------------------------------------------
-- conversation_members: membership, role and per-user receipt watermarks.
-- ---------------------------------------------------------------------------
CREATE TABLE conversation_members (
  conversation_id    uuid NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
  user_id            uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role               text NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'admin', 'member')),
  -- "This user has read / received every message with seq <= N". Two integers
  -- per member replace a receipt row per message per reader.
  last_read_seq      bigint NOT NULL DEFAULT 0,
  last_delivered_seq bigint NOT NULL DEFAULT 0,
  joined_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conversation_id, user_id)
);

-- The primary key answers "is user U in conversation C" and "who is in C".
-- This one answers "which conversations is U in" (sidebar, room joins).
CREATE INDEX conversation_members_user_idx ON conversation_members (user_id);

-- A group can never end up with two owners, whatever the application does.
CREATE UNIQUE INDEX conversation_members_one_owner_idx
  ON conversation_members (conversation_id) WHERE role = 'owner';

-- ---------------------------------------------------------------------------
-- messages
-- ---------------------------------------------------------------------------
CREATE TABLE messages (
  -- Generated by the sending client. A retry re-sends the same id, so the
  -- primary key is the idempotency key.
  id              uuid PRIMARY KEY,
  -- Inserts are serialised per conversation (the sender locks the conversation
  -- row first), so seq is strictly increasing in commit order within one.
  seq             bigint GENERATED ALWAYS AS IDENTITY,
  conversation_id uuid NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
  sender_id       uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  type            text NOT NULL DEFAULT 'text' CHECK (type IN ('text', 'system')),
  body            text NOT NULL DEFAULT '' CHECK (char_length(body) <= 4000),
  created_at      timestamptz NOT NULL DEFAULT now(),
  edited_at       timestamptz,
  -- Soft delete: the row stays as a tombstone so history and cursors are stable.
  deleted_at      timestamptz
);

-- Serves history pagination (seq < cursor ORDER BY seq DESC LIMIT n), the
-- "latest message" lookup and the unread count (seq > last_read_seq).
CREATE UNIQUE INDEX messages_conversation_seq_idx ON messages (conversation_id, seq);

-- ---------------------------------------------------------------------------
-- message_reactions: the primary key makes "add" idempotent.
-- ---------------------------------------------------------------------------
CREATE TABLE message_reactions (
  message_id uuid NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
  user_id    uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  emoji      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (message_id, user_id, emoji)
);

-- ---------------------------------------------------------------------------
-- attachments: uploaded first, then claimed by exactly one message.
-- ---------------------------------------------------------------------------
CREATE TABLE attachments (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id uuid NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
  uploader_id     uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- UNIQUE doubles as the index for "attachment of message M".
  message_id      uuid UNIQUE REFERENCES messages (id) ON DELETE CASCADE,
  original_name   text NOT NULL,
  mime_type       text NOT NULL,
  size_bytes      integer NOT NULL CHECK (size_bytes > 0),
  -- Random file name on disk; never derived from user input.
  storage_key     text NOT NULL UNIQUE,
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX attachments_conversation_idx ON attachments (conversation_id);
